    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        javax.swing.JPasswordField senhaAdmin = new javax.swing.JPasswordField();
        int opcao = javax.swing.JOptionPane.showConfirmDialog(this, senhaAdmin,
                "Confirmação do administrador para cadastro", javax.swing.JOptionPane.OK_CANCEL_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);
        if (opcao != javax.swing.JOptionPane.OK_OPTION) return;
        String senha = new String(senhaAdmin.getPassword());
        try {
            java.util.Optional<model.Utilizador> administrador = loginController.autenticar("admin", senha);
            if (administrador.isEmpty()
                    || administrador.get().getPerfil() == null
                    || administrador.get().getPerfil().getNivelAcesso() != model.enums.NivelAcesso.ADMINISTRADOR) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Senha do administrador incorreta.", "Acesso negado", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            new telaCadastro().setVisible(true);
            dispose();
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Não foi possível validar o administrador. Verifique a base de dados.\n" + ex.getMessage(),
                    "Erro de cadastro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = jTextField1.getText().trim();
        String senha = new String(jPasswordField1.getPassword());
        try {
            java.util.Optional<model.Utilizador> autenticado = loginController.autenticar(username, senha);
            if (autenticado.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Utilizador ou senha inválidos, ou conta inativa.", "Falha de autenticação", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            model.Utilizador utilizador = autenticado.get();
            model.enums.NivelAcesso nivel = utilizador.getPerfil() == null ? null : utilizador.getPerfil().getNivelAcesso();
            if (nivel == null || nivel == model.enums.NivelAcesso.CONSULTA) {
                javax.swing.JOptionPane.showMessageDialog(this, "A conta não tem um dos três níveis de acesso autorizados (Administrador, Gestor ou Operador).", "Acesso negado", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            telaPricipal principal = new telaPricipal(nivel);
            principal.setVisible(true);
            dispose();
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Não foi possível autenticar. Verifique a base de dados e as credenciais.\n" + ex.getMessage(), "Erro de acesso", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

