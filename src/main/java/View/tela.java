    private void animarBotoes(java.awt.Container container) {
        for (java.awt.Component componente : container.getComponents()) {
            if (componente instanceof javax.swing.JButton botao) {
                java.awt.Color original = botao.getBackground();
                botao.setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR));
                botao.setFocusPainted(false);
                botao.addMouseListener(new java.awt.event.MouseAdapter() {
                    @Override public void mouseEntered(java.awt.event.MouseEvent e) { if (botao.isEnabled()) botao.setBackground(new java.awt.Color(0, 145, 75)); }
                    @Override public void mouseExited(java.awt.event.MouseEvent e) { botao.setBackground(original); }
                });
            }
            if (componente instanceof java.awt.Container filho) animarBotoes(filho);
        }
    }

