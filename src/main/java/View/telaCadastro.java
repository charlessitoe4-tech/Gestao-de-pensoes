    private void animarBotoesRecursivamente(java.awt.Container container) {
        for (java.awt.Component componente : container.getComponents()) {
            if (componente instanceof javax.swing.JButton botao) {
                java.awt.Color normal = botao.getBackground();
                java.awt.Color hover = new java.awt.Color(0, 145, 75);
                botao.setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR));
                botao.setFocusPainted(false);
                botao.addMouseListener(new java.awt.event.MouseAdapter() {
                    @Override
                    public void mouseEntered(java.awt.event.MouseEvent e) {
                        if (botao.isEnabled()) {
                            botao.setBackground(hover);
                        }
                    }

                    @Override
                    public void mouseExited(java.awt.event.MouseEvent e) {
                        botao.setBackground(normal);
                    }
                });
            }
            if (componente instanceof java.awt.Container filho) {
                animarBotoesRecursivamente(filho);
            }
        }
    }

