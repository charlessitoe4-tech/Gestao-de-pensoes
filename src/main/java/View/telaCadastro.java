    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nome = jTextField1.getText().trim();
        String telefone = jTextField2.getText().trim();
        String email = jTextField3.getText().trim().toLowerCase(java.util.Locale.ROOT);
        String senha = new String(jTextField6.getPassword());
        String confirmar = new String(jTextField5.getPassword());
        if (nome.isBlank() || email.isBlank() || senha.isBlank() || confirmar.isBlank()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha nome, email e as duas senhas.", "Dados obrigatórios", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!email.matches("^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Introduza um email válido.", "Email inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (senha.length() < 8 || !senha.equals(confirmar)) {
            javax.swing.JOptionPane.showMessageDialog(this, "As senhas devem coincidir e ter pelo menos 8 caracteres.", "Senha inválida", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        String username = email.substring(0, email.indexOf('@')).replaceAll("[^a-zA-Z0-9._-]", "");
        if (username.isBlank()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Não foi possível gerar um nome de utilizador a partir do email.", "Utilizador inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            controller.UtilizadorController utilizadores = new controller.UtilizadorController();
            if (utilizadores.buscarPorUsername(username).isPresent()
                    || utilizadores.listar().stream().anyMatch(u -> email.equalsIgnoreCase(u.getEmail()))) {
                javax.swing.JOptionPane.showMessageDialog(this, "Já existe uma conta com este utilizador ou email. Use outro email.", "Utilizador existente", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            dao.PerfilDAO perfilDAO = new dao.HibernatePerfilDAO();
            model.enums.NivelAcesso nivel = switch (String.valueOf(jComboBox1.getSelectedItem())) {
                case "Administrador" ->
                    model.enums.NivelAcesso.ADMINISTRADOR;
                case "Gestor" ->
                    model.enums.NivelAcesso.GESTOR;
                default ->
                    model.enums.NivelAcesso.OPERADOR;
            };
            String nomePerfil = switch (nivel) {
                case ADMINISTRADOR ->
                    "Administrador";
                case GESTOR ->
                    "Gestor";
                default ->
                    "Operador";
            };
            model.Perfil perfil = perfilDAO.buscarPorNome(nomePerfil).orElseThrow(
                    () -> new IllegalStateException("Perfil não encontrado: " + nomePerfil));
            model.Utilizador novo = new model.Utilizador();
            novo.setNome(nome);
            novo.setUsername(username);
            novo.setEmail(email);
            novo.setTelefone(telefone);
            novo.setSenhaHash(Util.PasswordUtil.gerarHash(senha));
            novo.setPerfil(perfil);
            novo.setAtivo(true);
            novo.setDataCriacao(java.time.LocalDateTime.now());
            utilizadores.guardar(novo);
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Utilizador criado com sucesso.\nNome de utilizador: " + username,
                    "Cadastro concluído", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            new tela().setVisible(true);
            dispose();
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Não foi possível criar o utilizador. Verifique os dados e a base de dados.\n" + ex.getMessage(), "Erro de cadastro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

