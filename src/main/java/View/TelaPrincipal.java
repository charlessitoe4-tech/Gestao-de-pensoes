    /** Lê uma data AAAA-MM-DD de um campo; devolve null se vazio e não obrigatória. */
    private LocalDate lerData(javax.swing.JTextField campo, String nome, boolean obrigatoria) {
        String texto = campo.getText().trim();
        if (texto.isEmpty()) {
            if (obrigatoria) throw new IllegalArgumentException("Preencha: " + nome + ".");
            return null;
        }
        try {
            return LocalDate.parse(texto);
        } catch (DateTimeParseException ex) {
            throw new IllegalArgumentException(nome + " inválida. Use o formato AAAA-MM-DD.");
        }
    }

    /** Pede ao utilizador o valor mensal, que não existe como campo nestes formulários. */
    private java.math.BigDecimal pedirValorMensal() {
        String texto = JOptionPane.showInputDialog(this, "Valor mensal da pensão (MT):",
                "Valor mensal", JOptionPane.QUESTION_MESSAGE);
        if (texto == null) return null;
        try {
            java.math.BigDecimal valor = new java.math.BigDecimal(texto.trim().replace(',', '.'));
            if (valor.signum() <= 0) throw new NumberFormatException();
            return valor;
        } catch (NumberFormatException ex) {
            throw new IllegalArgumentException("O valor mensal deve ser um número superior a zero.");
        }
    }

    private static String numeroProcessoNovo(String prefixo) {
        return prefixo + "-" + java.time.LocalDateTime.now()
                .format(java.time.format.DateTimeFormatter.ofPattern("yyyyMMddHHmmss"));
    }

    private static void anexar(StringBuilder obs, String rotulo, String valor) {
        if (valor != null && !valor.isBlank()) obs.append(rotulo).append(": ").append(valor.trim()).append("; ");
    }

    /** Guarda o processo de pensão por aposentadoria (separador "pensão por aposentadoria"). */
    private void guardarPensaoAposentadoria() {
        try {
            if (jComboBox18.getSelectedIndex() <= 0) {
                throw new IllegalArgumentException("Selecione o beneficiário que pede a aposentadoria.");
            }
            Long beneficiarioId = extrairIdBeneficiario(jComboBox18.getSelectedItem());
            if (beneficiarioId == null) throw new IllegalArgumentException("Beneficiário inválido.");
            LocalDate dataPedido = lerData(jTextField46, "Data do pedido", true);
            int anos;
            try {
                anos = Integer.parseInt(jTextField47.getText().trim());
                if (anos < 0) throw new NumberFormatException();
            } catch (NumberFormatException ex) {
                throw new IllegalArgumentException("Anos de contribuição deve ser um número inteiro (0 ou mais).");
            }
            LocalDate dataPrevista = lerData(jTextField48, "Data prevista para a aposentadoria", false);
            if (dataPrevista != null && dataPrevista.isBefore(dataPedido)) {
                throw new IllegalArgumentException("A data prevista não pode ser anterior à data do pedido.");
            }
            if (!pensaoController.pesquisar("", model.enums.TipoPensao.VELHICE.name(), null, beneficiarioId).isEmpty()) {
                throw new IllegalArgumentException("Este beneficiário já tem um processo de pensão por aposentadoria.");
            }
            java.math.BigDecimal valor = pedirValorMensal();
            if (valor == null) return;
            StringBuilder obs = new StringBuilder();
            anexar(obs, "Situação indicada", jComboBox19.getSelectedIndex() <= 0 ? "" : String.valueOf(jComboBox19.getSelectedItem()));
            anexar(obs, "Data prevista da aposentadoria", dataPrevista == null ? "" : dataPrevista.toString());
            String numero = numeroProcessoNovo("PA");
            model.Pensao criada = pensaoController.guardar(null, numero, model.enums.TipoPensao.VELHICE,
                    beneficiarioId, valor, dataPedido, obs.toString().trim());
            if (criada instanceof model.PensaoVelhice velhice) {
                velhice.setAnosContribuicao(anos);
                pensaoController.guardar(velhice);
            }
            jTextField46.setText(""); jTextField47.setText(""); jTextField48.setText("");
            jComboBox18.setSelectedIndex(0); jComboBox19.setSelectedIndex(0);
            pesquisarProcessos();
            JOptionPane.showMessageDialog(this, "Pensão por aposentadoria registada. Processo nº " + numero + " (estado: Pendente).");
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException ex) {
            mostrarErro("Não foi possível guardar a pensão por aposentadoria.", ex);
        }
    }

    /** Guarda o processo de pensão por morte (separador "pensão por morte"). */
    private void guardarPensaoMorte() {
        try {
            if (jComboBox17.getSelectedIndex() <= 0) {
                throw new IllegalArgumentException("Selecione o beneficiário falecido.");
            }
            Long falecidoId = extrairIdBeneficiario(jComboBox17.getSelectedItem());
            if (falecidoId == null) throw new IllegalArgumentException("Beneficiário falecido inválido.");
            String nomeRequerente = jTextField33.getText().trim();
            String biRequerente = jTextField34.getText().trim();
            String parentesco = jTextField36.getText().trim();
            if (nomeRequerente.isEmpty() || biRequerente.isEmpty() || parentesco.isEmpty()) {
                throw new IllegalArgumentException("Preencha o nome, o bilhete de identidade e o parentesco do requerente.");
            }
            LocalDate dataPedido = lerData(jTextField23, "Data do pedido", true);
            Beneficiario requerente = null;
            for (Beneficiario b : beneficiarioController.pesquisar(biRequerente)) {
                if (b.getNumeroBI() != null && b.getNumeroBI().trim().equalsIgnoreCase(biRequerente)) {
                    requerente = b;
                    break;
                }
            }
            if (requerente == null) {
                throw new IllegalArgumentException("O requerente ainda não está registado. Registe-o primeiro no menu Benefícios (BI " + biRequerente + ").");
            }
            if (falecidoId.equals(requerente.getId())) {
                throw new IllegalArgumentException("O requerente não pode ser a mesma pessoa que o falecido.");
            }
            final Long requerenteId = requerente.getId();
            for (model.Pensao existente : pensaoController.pesquisar("", model.enums.TipoPensao.SOBREVIVENCIA.name(), null, requerenteId)) {
                if (existente instanceof model.PensaoSobrevivencia ps && falecidoId.equals(ps.getFalecidoId())) {
                    throw new IllegalArgumentException("Já existe um processo de pensão por morte deste falecido para este requerente.");
                }
            }
            java.math.BigDecimal valor = pedirValorMensal();
            if (valor == null) return;
            StringBuilder obs = new StringBuilder();
            anexar(obs, "Requerente", nomeRequerente);
            anexar(obs, "Parentesco", parentesco);
            anexar(obs, "Contacto", jTextField35.getText());
            anexar(obs, "Endereço", jTextField30.getText());
            anexar(obs, "Distrito", jTextField31.getText());
            anexar(obs, "Província", jTextField32.getText());
            anexar(obs, "Anos de contribuição do falecido", jTextField28.getText());
            anexar(obs, "Situação indicada", jComboBox11.getSelectedIndex() <= 0 ? "" : String.valueOf(jComboBox11.getSelectedItem()));
            String numero = numeroProcessoNovo("PM");
            model.Pensao criada = pensaoController.guardar(null, numero, model.enums.TipoPensao.SOBREVIVENCIA,
                    requerenteId, valor, dataPedido, obs.toString().trim());
            if (criada instanceof model.PensaoSobrevivencia sobrevivencia) {
                sobrevivencia.setFalecidoId(falecidoId);
                pensaoController.guardar(sobrevivencia);
            }
            for (javax.swing.JTextField campo : new javax.swing.JTextField[]{jTextField23, jTextField28, jTextField29,
                    jTextField30, jTextField31, jTextField32, jTextField33, jTextField34, jTextField35, jTextField36}) {
                campo.setText("");
            }
            jComboBox17.setSelectedIndex(0); jComboBox11.setSelectedIndex(0);
            pesquisarProcessos();
            JOptionPane.showMessageDialog(this, "Pensão por morte registada. Processo nº " + numero + " (estado: Pendente).");
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException ex) {
            mostrarErro("Não foi possível guardar a pensão por morte.", ex);
        }
    }

