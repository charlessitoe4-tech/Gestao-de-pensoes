    /** Preenche os seletores de Beneficiario com os registos persistidos, sem dados de demonstração. */
    private void carregarBeneficiariosNosCombos() {
        try {
            List<Beneficiario> beneficiarios = beneficiarioController.listar();
            DefaultComboBoxModel<String> modeloIds = new DefaultComboBoxModel<>();
            DefaultComboBoxModel<String> modeloNomes = new DefaultComboBoxModel<>();
            modeloIds.addElement("Selecione o Beneficiário");
            modeloNomes.addElement("Selecione o Beneficiário");
            for (Beneficiario beneficiario : beneficiarios) {
                String idNome = beneficiario.getId() + " - " + beneficiario.getNomeCompleto().trim();
                modeloIds.addElement(String.valueOf(beneficiario.getId()));
                modeloNomes.addElement(idNome);
            }
            aplicarModelo(jComboBox5, modeloIds);
            aplicarModelo(jComboBox17, modeloIds);
            aplicarModelo(jComboBox18, modeloIds);
            aplicarModelo(jComboBox10, modeloNomes);
            aplicarModelo(jComboBox15, modeloNomes);
            atualizarTabelaBeneficiarios(beneficiarios);
        } catch (RuntimeException ex) {
            logger.log(java.util.logging.Level.WARNING, "Não foi possível carregar os Beneficiários.", ex);
        }
    }

    private void aplicarModelo(javax.swing.JComboBox<String> combo, DefaultComboBoxModel<String> modelo) {
        if (combo != null) combo.setModel(modelo);
    }

    /** Persiste o formulário de Beneficiario depois de validar os campos obrigatórios. */
    private void guardarBeneficiario() {
        try {
            String nome = jTextField1.getText().trim();
            String bi = jTextField2.getText().trim();
            String data = jTextField3.getText().trim();
            String generoTexto = String.valueOf(jComboBox1.getSelectedItem());
            String estadoTexto = String.valueOf(jComboBox4.getSelectedItem());
            if (nome.isBlank() || bi.isBlank() || data.isBlank()
                    || jComboBox1.getSelectedIndex() <= 0 || jComboBox4.getSelectedIndex() <= 0) {
                throw new IllegalArgumentException("Preencha nome, BI, data de nascimento, sexo e Estado civil.");
            }
            beneficiarioController.guardar(beneficiarioSelecionadoId, nome, bi, "", data,
                    normalizarGenero(generoTexto), normalizarEstadoCivil(estadoTexto),
                    jTextField7.getText(), jTextField8.getText(), jTextField9.getText(),
                    jComboBox3.getSelectedIndex() <= 0 ? "" : String.valueOf(jComboBox3.getSelectedItem()), "", "");
            carregarBeneficiariosNosCombos();
            limparFormularioBeneficiario();
            JOptionPane.showMessageDialog(this, "Beneficiário registado com sucesso.");
        } catch (DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Data inválida. Use o formato AAAA-MM-DD.", "Validação", JOptionPane.WARNING_MESSAGE);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Falha ao guardar Beneficiário.", ex);
            JOptionPane.showMessageDialog(this, "Não foi possível guardar o Beneficiário. Verifique os dados e a ligação à base de dados.", "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private String normalizarGenero(String texto) {
        return switch (texto.toLowerCase(java.util.Locale.ROOT)) {
            case "masculino" -> Genero.MASCULINO.name();
            case "feminino" -> Genero.FEMININO.name();
            default -> Genero.OUTRO.name();
        };
    }

    private String normalizarEstadoCivil(String texto) {
        String valor = texto.toLowerCase(java.util.Locale.ROOT);
        if (valor.contains("casado")) return EstadoCivil.CASADO.name();
        if (valor.contains("divor")) return EstadoCivil.DIVORCIADO.name();
        if (valor.contains("viúvo") || valor.contains("viúvo")) return EstadoCivil.VIUVO.name();
        if (valor.contains("união") || valor.contains("uniao")) return EstadoCivil.UNIAO_FACTO.name();
        return EstadoCivil.SOLTEIRO.name();
    }

    private void atualizarTabelaBeneficiarios(List<Beneficiario> lista) {
        if (jTable2 == null) return;
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"ID", "Nome", "Nº BI", "Nacionalidade", "Sexo", "Estado civil", "Telefone", "E-mail", "Morada"}, 0) {
            @Override public boolean isCellEditable(int row, int column) { return false; }
        };
        for (Beneficiario b : lista) {
            modelo.addRow(new Object[]{b.getId(), b.getNomeCompleto().trim(), b.getNumeroBI(),
                b.getNacionalidade(), b.getGenero(), b.getEstadoCivil(), b.getTelefone(), b.getEmail(), b.getEndereco()});
        }
        jTable2.setModel(modelo);
    }

