    /** Efeitos visuais consistentes para todos os botões, sem interferir nos eventos do formulário. */
    private void configurarAnimacoesBotoes() {
        java.awt.Color normal = new java.awt.Color(0, 102, 51);
        java.awt.Color hover = new java.awt.Color(0, 145, 75);
        animarBotoesRecursivamente(getContentPane(), normal, hover);
    }

    private void animarBotoesRecursivamente(java.awt.Container container, java.awt.Color normal, java.awt.Color hover) {
        for (java.awt.Component componente : container.getComponents()) {
            if (componente instanceof javax.swing.JButton botao) {
                if (botao.isOpaque()) {
                    java.awt.Color corOriginal = botao.getBackground();
                    botao.setFocusPainted(false);
                    botao.setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR));
                    botao.setBorder(javax.swing.BorderFactory.createCompoundBorder(
                            javax.swing.BorderFactory.createLineBorder(new java.awt.Color(0, 80, 40, 70), 1, true),
                            javax.swing.BorderFactory.createEmptyBorder(5, 9, 5, 9)));
                    botao.addMouseListener(new java.awt.event.MouseAdapter() {
                        @Override public void mouseEntered(java.awt.event.MouseEvent e) {
                            if (botao.isEnabled()) { botao.setBackground(hover); botao.setForeground(java.awt.Color.WHITE); }
                        }
                        @Override public void mouseExited(java.awt.event.MouseEvent e) {
                            botao.setBackground(corOriginal == null ? normal : corOriginal);
                        }
                    });
                }
            }
            if (componente instanceof java.awt.Container filho) animarBotoesRecursivamente(filho, normal, hover);
        }
    }

