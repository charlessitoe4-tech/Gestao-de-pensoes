    /** Preenche os campos do formulário a partir do ID escolhido no seletor. */
    private void preencherDadosBeneficiarioSelecionado(javax.swing.JComboBox<String> combo, boolean falecido) {
        if (combo.getSelectedIndex() <= 0 || combo.getSelectedItem() == null) return;
        try {
            Long idSelecionado = extrairIdBeneficiario(combo.getSelectedItem());
            if (idSelecionado == null) throw new NumberFormatException("ID inválido");
            long id = idSelecionado;
            beneficiarioController.buscarPorId(id).ifPresent(b -> {
                String nome = b.getNomeCompleto().trim();
                String nascimento = b.getDataNascimento() == null ? "" : b.getDataNascimento().toString();
                String nacionalidade = b.getNacionalidade() == null ? "" : b.getNacionalidade();
                String endereco = b.getEndereco() == null ? "" : b.getEndereco();
                String Telefone = b.getTelefone() == null ? "" : b.getTelefone();
                String civil = b.getEstadoCivil() == null ? "" : b.getEstadoCivil().toString();
                int Idade = b.getDataNascimento() == null ? 0
                        : java.time.Period.between(b.getDataNascimento(), LocalDate.now()).getYears();
                if (falecido) {
                    jTextField18.setText(nome); jTextField19.setText(nascimento); jTextField20.setText(nacionalidade);
                    jTextField22.setText(endereco); jTextField24.setText(Idade == 0 ? "" : String.valueOf(Idade));
                    jTextField25.setText(civil); jTextField26.setText(Telefone);
                } else {
                    jTextField38.setText(nome); jTextField39.setText(nascimento); jTextField40.setText(nacionalidade);
                    jTextField41.setText(endereco); jTextField42.setText(Idade == 0 ? "" : String.valueOf(Idade));
                    jTextField43.setText(civil); jTextField44.setText(Telefone);
                }
            });
        } catch (NumberFormatException ex) {
            mostrarMensagem("O número de beneficiário selecionado é inválido.");
        } catch (RuntimeException ex) {
            mostrarErro("Não foi possível preencher os dados do beneficiário.", ex);
        }
    }

    /** Extrai o ID de um item de seletor no formato "12" ou "12 - Nome". */
    private static Long extrairIdBeneficiario(Object item) {
        if (item == null) return null;
        String texto = item.toString().trim();
        int separador = texto.indexOf(" - ");
        if (separador > 0) texto = texto.substring(0, separador).trim();
        try {
            return Long.parseLong(texto);
        } catch (NumberFormatException ex) {
            return null;
        }
    }

    /** Devolve o processo de pensão mais relevante do beneficiário (ativo, senão o mais recente). */
    private java.util.Optional<model.Pensao> pensaoDoBeneficiario(Long beneficiarioId) {
        if (beneficiarioId == null) return java.util.Optional.empty();
        List<model.Pensao> pensoes = pensaoController.pesquisar("", null, null, beneficiarioId);
        model.Pensao escolhida = null;
        for (model.Pensao pensao : pensoes) {
            boolean ativa = pensao.getEstado() == model.enums.EstadoPensao.ATIVA;
            boolean escolhidaAtiva = escolhida != null && escolhida.getEstado() == model.enums.EstadoPensao.ATIVA;
            if (escolhida == null || (ativa && !escolhidaAtiva)
                    || (ativa == escolhidaAtiva && pensao.getId() != null && escolhida.getId() != null
                        && pensao.getId() > escolhida.getId())) {
                escolhida = pensao;
            }
        }
        return java.util.Optional.ofNullable(escolhida);
    }

