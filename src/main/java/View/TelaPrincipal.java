    /** Copia o ficheiro escolhido para a pasta da aplicação e regista o documento do beneficiário. */
    private void guardarDocumento() {
        try {
            if (jComboBox5.getSelectedIndex() <= 0) {
                throw new IllegalArgumentException("Selecione o beneficiário a quem pertence o documento.");
            }
            Long pessoaId = extrairIdBeneficiario(jComboBox5.getSelectedItem());
            if (pessoaId == null) throw new IllegalArgumentException("Beneficiário inválido.");
            if (documentoParaGuardar == null || !documentoParaGuardar.isFile()) {
                throw new IllegalArgumentException("Selecione o ficheiro do documento com o botão \"selecionar ficheiro\".");
            }
            if (documentoParaGuardar.length() > 20L * 1024 * 1024) {
                throw new IllegalArgumentException("O ficheiro é demasiado grande (máximo 20 MB).");
            }
            model.enums.TipoDocumento[] tipos = model.enums.TipoDocumento.values();
            Object escolhido = JOptionPane.showInputDialog(this, "Tipo de documento:", "Guardar documento",
                    JOptionPane.QUESTION_MESSAGE, null, tipos, model.enums.TipoDocumento.OUTRO);
            if (escolhido == null) return;

            java.nio.file.Path pasta = java.nio.file.Path.of(System.getProperty("user.home"), ".gestao-pensoes", "documentos");
            java.nio.file.Files.createDirectories(pasta);
            String nomeSeguro = documentoParaGuardar.getName().replaceAll("[^A-Za-z0-9._-]", "_");
            java.nio.file.Path destino = pasta.resolve(pessoaId + "_" + System.currentTimeMillis() + "_" + nomeSeguro);
            java.nio.file.Files.copy(documentoParaGuardar.toPath(), destino);

            documentoController.guardar((model.enums.TipoDocumento) escolhido, jTextField21.getText(),
                    pessoaId, destino.toAbsolutePath().toString());

            documentoParaGuardar = null;
            jLabel35.setText("Área para carregar e pré-visualizar ficheiro");
            jLabel35.setToolTipText(null);
            atualizarTabelaDocumentos(pessoaId);
            JOptionPane.showMessageDialog(this, "Documento guardado com sucesso.");
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validação", JOptionPane.WARNING_MESSAGE);
        } catch (java.io.IOException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Falha ao copiar o documento.", ex);
            JOptionPane.showMessageDialog(this, "Não foi possível copiar o ficheiro para a pasta da aplicação.\n" + ex.getMessage(),
                    "Erro", JOptionPane.ERROR_MESSAGE);
        } catch (RuntimeException ex) {
            mostrarErro("Não foi possível guardar o documento.", ex);
        }
    }

    /** Mostra na tabela os documentos do beneficiário indicado (ou todos, se for null). */
    private void atualizarTabelaDocumentos(Long pessoaId) {
        if (jTable3 == null) return;
        try {
            DefaultTableModel modelo = new DefaultTableModel(
                    new Object[]{"ID", "Beneficiário", "Tipo", "Nº", "Ficheiro", "Caminho"}, 0) {
                @Override public boolean isCellEditable(int row, int column) { return false; }
            };
            List<model.Documento> documentos = pessoaId == null
                    ? documentoController.listar() : documentoController.listarPorPessoa(pessoaId);
            for (model.Documento d : documentos) {
                String nome = d.getPessoaId() == null ? "" : beneficiarioController.buscarPorId(d.getPessoaId())
                        .map(b -> b.getNomeCompleto().trim()).orElse(String.valueOf(d.getPessoaId()));
                String caminho = d.getCaminhoFicheiro() == null ? "" : d.getCaminhoFicheiro();
                modelo.addRow(new Object[]{d.getId(), nome, d.getTipo(), d.getNumero() == null ? "" : d.getNumero(),
                    java.nio.file.Path.of(caminho.isEmpty() ? "-" : caminho).getFileName().toString(), caminho});
            }
            jTable3.setModel(modelo);
            if (jTable3.getColumnCount() > 5) jTable3.removeColumn(jTable3.getColumnModel().getColumn(5));
        } catch (RuntimeException ex) {
            logger.log(java.util.logging.Level.WARNING, "Não foi possível carregar os documentos.", ex);
        }
    }

