    /** Aprova (estado Ativa) ou reprova (estado Cancelada) o processo selecionado na tabela. */
    private void decidirProcesso(boolean aprovar) {
        if (nivelAcesso != NivelAcesso.ADMINISTRADOR && nivelAcesso != NivelAcesso.GESTOR) {
            mostrarMensagem("Só o Administrador e o Gestor podem decidir processos.");
            return;
        }
        int linha = jTable1.getSelectedRow();
        if (linha < 0 || pensaoSelecionadaId == null) {
            mostrarMensagem("Selecione um processo na lista de pensões antes de decidir.");
            return;
        }
        final Long id = pensaoSelecionadaId;
        String acao = aprovar ? "aprovar" : "reprovar";
        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Deseja " + acao + " o processo selecionado?", "Confirmar decisão", JOptionPane.YES_NO_OPTION);
        if (confirmacao != JOptionPane.YES_OPTION) return;
        try {
            if (aprovar) pensaoController.aprovar(id); else pensaoController.cancelar(id);
            pesquisarProcessos();
            for (int i = 0; i < jTable1.getRowCount(); i++) {
                Object valor = jTable1.getValueAt(i, 0);
                if (valor instanceof Number n && n.longValue() == id) {
                    jTable1.setRowSelectionInterval(i, i);
                    break;
                }
            }
            JOptionPane.showMessageDialog(this, aprovar
                    ? "Processo aprovado: a pensão passou ao estado ATIVA."
                    : "Processo reprovado: a pensão passou ao estado CANCELADA.");
        } catch (IllegalStateException | java.util.NoSuchElementException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Decisão não permitida", JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException ex) {
            mostrarErro("Não foi possível guardar a decisão.", ex);
        }
    }

